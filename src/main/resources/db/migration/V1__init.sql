CREATE TABLE book (
    -- BY DEFAULT (not ALWAYS) so the seed can insert fixed ids
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(255) NOT NULL,
    author            VARCHAR(255) NOT NULL,
    difficulty        VARCHAR(20)  NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    UNIQUE (title, author) -- the same book can't be added twice
);

CREATE TABLE book_category (
    book_id  BIGINT       NOT NULL REFERENCES book (id) ON DELETE CASCADE,
    category VARCHAR(50)  NOT NULL,
    PRIMARY KEY (book_id, category)
);

CREATE TABLE section (
    book_id    BIGINT      NOT NULL REFERENCES book (id) ON DELETE CASCADE,
    section_id INT         NOT NULL,
    text       TEXT        NOT NULL,
    type       VARCHAR(10) NOT NULL CHECK (type IN ('BEGIN', 'NODE', 'END')),
    -- gotoId lives inside this JSON, so the book validator (not a FK) rejects broken links
    options    JSONB,
    PRIMARY KEY (book_id, section_id)
);
