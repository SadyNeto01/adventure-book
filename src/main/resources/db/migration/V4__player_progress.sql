CREATE TABLE player_progress (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id          BIGINT      NOT NULL REFERENCES player (id) ON DELETE CASCADE,
    book_id            BIGINT      NOT NULL,
    current_section_id INT         NOT NULL,
    health             INT         NOT NULL DEFAULT 10,
    status             VARCHAR(20) NOT NULL CHECK (status IN ('IN_PROGRESS', 'DEAD', 'FINISHED')),
    updated_at         TIMESTAMPTZ NOT NULL,
    UNIQUE (player_id, book_id), -- one progress per book; starting again resets it
    FOREIGN KEY (book_id, current_section_id) REFERENCES section (book_id, section_id) ON DELETE CASCADE
);
